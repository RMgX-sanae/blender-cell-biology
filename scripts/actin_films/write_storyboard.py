def main():
    audio=ROOT/'audio';audio.mkdir(exist_ok=True)
    for s in SHOTS:
        s['beat_boundaries']={'a03':[0,.10,.31,1],'a04':[0,.34,.41,1],
            'a08':[0,.10,.65,1],'c04':[0,.36,.66,1]}.get(s['id'],[0,1/3,2/3,1])
        transcript=audio/(s['id']+'.txt');transcript.write_text(s['narration'])
        raw=audio/(s['id']+'.aiff');wav=audio/(s['id']+'.wav')
        if OPTIONS['narration'] == 'macos':
            if not wav.exists():
                subprocess.run(['say','-v',OPTIONS['voice'],'-r','175','-f',str(transcript),'-o',str(raw)],check=True)
                subprocess.run([FFMPEG,'-y','-v','error','-i',str(raw),'-ar','48000','-ac','1',str(wav)],check=True)
            with wave.open(str(wav),'rb') as w: duration=w.getnframes()/w.getframerate()
        elif OPTIONS['narration'] == 'provided':
            with wave.open(str(wav),'rb') as w: duration=w.getnframes()/w.getframerate()
        else:
            duration=0
        s['voice_seconds']=duration;s['seconds']=math.ceil(max(s['minimum_seconds'],duration+1.5))
        s['fps']=OPTIONS['fps'];s['frames']=s['seconds']*s['fps']
        s['voice']=OPTIONS['narration']
    data={'shots':SHOTS,'routes':ROUTES,'representation':'Source-derived molecular teaching with explicit schematic mechanisms.'}
    (ROOT/'storyboard.json').write_text(json.dumps(data,ensure_ascii=False,indent=2)+'\n')
    for name,r in ROUTES.items():
        byid={s['id']:s for s in SHOTS}
        print(name,sum(byid[i]['seconds'] for i in r['shots']),'seconds',len(r['shots']),'chapters')

if __name__=='__main__':main()
